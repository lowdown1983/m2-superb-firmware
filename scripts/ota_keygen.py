#!/usr/bin/env python3
"""Generate the SuperB OTA signing keypair (Phase 11).

SECURITY RULE (standing): the private key NEVER lives inside the firmware
tree or any distributed zip. It is written to ~/workspace/.ota-keys/
(outside the project) with mode 0600. Only the PUBLIC key is baked into
the firmware (src/superb/ota_pubkey.h, generated by this script).

Curve: NIST P-256 (secp256r1) + SHA-256, matching the ESP32's mbedTLS
ECDSA verification (same scheme as ESP-IDF secure boot).

Usage:
    python3 scripts/ota_keygen.py [--force]

    --force  overwrite an existing keypair (the old public key in the
             firmware will no longer verify new images — reflash needed)

Requires: cryptography (pip install cryptography)
"""
import argparse
import hashlib
import os
import stat
import sys

try:
    from cryptography.hazmat.primitives.asymmetric import ec
    from cryptography.hazmat.primitives import serialization
except ImportError:
    sys.exit("need 'cryptography': pip install cryptography")

KEY_DIR = os.path.expanduser("~/.ota-keys")  # OUTSIDE the firmware tree
PRIV_PATH = os.path.join(KEY_DIR, "superb_ota_priv.pem")
PROJ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUB_HDR = os.path.join(PROJ, "src", "superb", "ota_pubkey.h")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true",
                    help="overwrite an existing keypair")
    args = ap.parse_args()

    if os.path.exists(PRIV_PATH) and not args.force:
        sys.exit(f"refusing: {PRIV_PATH} exists (use --force to rotate)")

    os.makedirs(KEY_DIR, mode=0o700, exist_ok=True)
    priv = ec.generate_private_key(ec.SECP256R1())
    pem = priv.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.TraditionalOpenSSL,
        serialization.NoEncryption())
    with open(PRIV_PATH, "wb") as f:
        f.write(pem)
    os.chmod(PRIV_PATH, 0o600)

    nums = priv.public_key().public_numbers()
    x = nums.x.to_bytes(32, "big")
    y = nums.y.to_bytes(32, "big")
    fp = hashlib.sha256(b"\x04" + x + y).hexdigest()[:16]

    def c_arr(name, data):
        rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 12])
                for i in range(0, len(data), 12)]
        return (f"constexpr uint8_t {name}[{len(data)}] = {{\n    " +
                ",\n    ".join(rows) + "\n};")

    hdr = (f"// GENERATED by scripts/ota_keygen.py — do not hand-edit.\n"
           f"// SuperB OTA ECDSA P-256 public key (uncompressed X||Y, 64 bytes).\n"
           f"// Key fingerprint (SHA256(pub)[0:8] hex): {fp}\n"
           f"// The PRIVATE key lives at ~/.ota-keys/superb_ota_priv.pem\n"
           f"// (outside the firmware tree; never distributed).\n"
           f"#pragma once\n"
           f"#include <stdint.h>\n\n"
           f"{c_arr('OTA_PUBKEY', x + y)}\n"
           f"// Fingerprint string shown in the /ota web UI.\n"
           f'constexpr char OTA_KEY_FP[] = "{fp}";\n')
    with open(PUB_HDR, "w") as f:
        f.write(hdr)

    st = os.stat(PRIV_PATH)
    assert stat.S_IMODE(st.st_mode) == 0o600, "private key perms wrong"
    print(f"private key: {PRIV_PATH} (0600, outside firmware tree)")
    print(f"public key:  {PUB_HDR}")
    print(f"fingerprint: {fp}")
    print("Keep the private key on Marcus's machine only. "
          "It is excluded from all zips by location (~/workspace/.ota-keys/).")


if __name__ == "__main__":
    main()
