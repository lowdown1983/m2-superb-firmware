struct MitmRule {
    uint8_t idx = 0;
    uint32_t id = 0, mask = 0;
    uint8_t dir = 2, action = 0, modOff = 0, modMask = 0, modVal = 0;
    uint16_t rateLim = 0;
    uint32_t hits = 0;
};

struct MitmStatus {
    bool ok = false;
    uint32_t fwdAB = 0, fwdBA = 0, dropAB = 0, dropBA = 0;
    uint32_t modAB = 0, modBA = 0, loopSupp = 0, rateDrop = 0;
    uint8_t loadA = 0, loadB = 0, dir = 2, stealth = 1, nRules = 0;
    uint32_t baudA = 500000, baudB = 500000;
    uint16_t loopWin = 5, defRate = 0;
    uint8_t active = 0;
    MitmRule rules[8];
    uint8_t nRulesGot = 0;
};
MitmStatus mitmSt;

static uint32_t le32(const uint8_t* p)
{
    return (uint32_t)p[0] | ((uint32_t)p[1] << 8) |
           ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
}

bool fetchMitmStats()
{
    uint8_t resp[64]; uint8_t rlen = 0;
    if (!mmcTransact(mmc::CMD_MITM_STATS, nullptr, 0, resp, sizeof(resp), rlen) ||
        rlen < 39 || resp[0] != (mmc::CMD_MITM_STATS | 0x80) ||
        resp[1] != mmc::ST_OK) {
        mitmSt.ok = false;
        return false;
    }
    mitmSt.ok = true;
    mitmSt.fwdAB = le32(resp + 2);  mitmSt.fwdBA = le32(resp + 6);
    mitmSt.dropAB = le32(resp + 10); mitmSt.dropBA = le32(resp + 14);
    mitmSt.modAB = le32(resp + 18); mitmSt.modBA = le32(resp + 22);
    mitmSt.loopSupp = le32(resp + 26); mitmSt.rateDrop = le32(resp + 30);
    mitmSt.loadA = resp[34]; mitmSt.loadB = resp[35];
    mitmSt.dir = resp[36]; mitmSt.stealth = resp[37]; mitmSt.nRules = resp[38];
    // Config readback (prefill the form honestly).
    if (mmcTransact(mmc::CMD_MITM_CFG, nullptr, 0, resp, sizeof(resp), rlen) &&
        rlen >= 17 && resp[0] == (mmc::CMD_MITM_CFG | 0x80) &&
        resp[1] == mmc::ST_OK) {
        mitmSt.baudA = le32(resp + 2); mitmSt.baudB = le32(resp + 6);
        mitmSt.dir = resp[10]; mitmSt.stealth = resp[11];
        mitmSt.loopWin = (uint16_t)resp[12] | ((uint16_t)resp[13] << 8);
        mitmSt.defRate = (uint16_t)resp[14] | ((uint16_t)resp[15] << 8);
        mitmSt.active = resp[16];
    }
    // Rule list (2 per reply).
    mitmSt.nRulesGot = 0;
    for (uint8_t start = 0; start < 8; start += 2) {
        uint8_t req[1] = { start };
        if (!mmcTransact(mmc::CMD_MITM_RULE_LIST, req, 1, resp, sizeof(resp), rlen) ||
            rlen < 4 || resp[0] != (mmc::CMD_MITM_RULE_LIST | 0x80) ||
            resp[1] != mmc::ST_OK)
            break;
        uint8_t nTotal = resp[2], nRet = resp[3];
        if (nRet > 2) nRet = 2;
        for (uint8_t i = 0; i < nRet && mitmSt.nRulesGot < 8; i++) {
            const uint8_t* e = resp + 4 + i * 20;
            MitmRule& r = mitmSt.rules[mitmSt.nRulesGot++];
            r.idx = e[0];
            r.id = le32(e + 1); r.mask = le32(e + 5);
            r.dir = e[9]; r.action = e[10];
            r.modOff = e[11]; r.modMask = e[12]; r.modVal = e[13];
            r.rateLim = (uint16_t)e[14] | ((uint16_t)e[15] << 8);
            r.hits = le32(e + 16);
        }
        if (start + nRet >= nTotal) break;
    }
    return true;
}

