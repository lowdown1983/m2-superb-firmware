// Download one log file with format conversion.
void handleLogDl()
{
    String f = webServer.arg("f");      // "00".."01"
    String fmt = webServer.arg("fmt");  // native|gvret|crtd|csv
    int idx = f.toInt();
    if (idx < 0 || idx >= p12::LOG_FILE_N) {
        webServer.send(400, "text/plain", "bad file");
        return;
    }
    char path[32];
    p12::logPath((uint8_t)idx, path, sizeof(path));
    File fh = SPIFFS.open(path, "r");
    if (!fh) {
        webServer.send(404, "text/plain", "no such log");
        return;
    }
    if (fmt == "native") {
        webServer.sendHeader("Content-Disposition",
                             ("attachment; filename=log_" + f + ".bin").c_str());
        // Files are <= 64 KB; read-and-send works on real + sim WebServer.
        String blob;
        uint8_t chunk[256];
        size_t n;
        while ((n = fh.read(chunk, sizeof(chunk))) > 0)
            for (size_t i = 0; i < n; i++) blob += (char)chunk[i];
        fh.close();
        webServer.send(200, "application/octet-stream", blob);
        return;
    }
    // Converted formats: stream text built in RAM (files are <= 64 KB).
    String out;
    uint8_t rec[p12::REC_BYTES];
    char line[128];
    while (fh.read(rec, p12::REC_BYTES) == p12::REC_BYTES) {
        uint32_t tsMs = (uint32_t)rec[0] | ((uint32_t)rec[1] << 8) |
                        ((uint32_t)rec[2] << 16) | ((uint32_t)rec[3] << 24);
        uint8_t bus = rec[4], dir = rec[5], kind = rec[6], ecu = rec[7];
        uint16_t svc = rec[8] | ((uint16_t)rec[9] << 8);
        int32_t val = (int32_t)((uint32_t)rec[10] | ((uint32_t)rec[11] << 8) |
                                ((uint32_t)rec[12] << 16) | ((uint32_t)rec[13] << 24));
        uint8_t rawLen = rec[14] > 8 ? 8 : rec[14];
        char rawHex[17];
        for (uint8_t i = 0; i < rawLen; i++)
            snprintf(rawHex + i * 2, 3, "%02X", rec[15 + i]);
        rawHex[rawLen * 2] = '\0';
        if (fmt == "csv") {
            snprintf(line, sizeof(line), "%lu,%u,%u,%u,%u,0x%04X,%ld,%s\r\n",
                     (unsigned long)tsMs, bus, dir, kind, ecu, svc,
                     (long)val, rawHex);
            out += line;
        } else if (fmt == "crtd") {
            // SavvyCAN capture text. kind 0 carries a CAN frame (ID low
            // 16 in svc — documented truncation); others become comments.
            if (kind == 0) {
                snprintf(line, sizeof(line), "(%lu.%03lu) can%u %X#%s\r\n",
                         (unsigned long)(tsMs / 1000),
                         (unsigned long)(tsMs % 1000), bus, svc, rawHex);
            } else {
                snprintf(line, sizeof(line),
                         "# %lu kind=%u ecu=%u svc=0x%04X val=%ld %s\r\n",
                         (unsigned long)tsMs, kind, ecu, svc, (long)val,
                         rawHex);
            }
            out += line;
        } else if (fmt == "gvret") {
            // M2RET binary frame: F1 00 <tsUs LE32> <id LE32> <bus>
            // <len> <data>. kind-0 only; others are skipped (binary has
            // no comments). ID is the low 16 bits (record truncation).
            if (kind != 0) continue;
            uint8_t fr[16];
            fr[0] = 0xF1;
            fr[1] = 0x00;
            uint32_t tsUs = tsMs * 1000UL;
            fr[2] = tsUs & 0xFF; fr[3] = (tsUs >> 8) & 0xFF;
            fr[4] = (tsUs >> 16) & 0xFF; fr[5] = (tsUs >> 24) & 0xFF;
            fr[6] = svc & 0xFF; fr[7] = (svc >> 8) & 0xFF;
            fr[8] = 0; fr[9] = 0;
            fr[10] = bus;
            fr[11] = rawLen;
            for (uint8_t i = 0; i < rawLen; i++) fr[12 + i] = rec[15 + i];
            // Accumulate as Latin-1 chars (binary-safe for String).
            for (uint8_t i = 0; i < 12 + rawLen; i++) out += (char)fr[i];
        } else {
            webServer.send(400, "text/plain", "bad fmt");
            fh.close();
            return;
        }
    }
    fh.close();
    webServer.sendHeader("Content-Disposition",
                         ("attachment; filename=log_" + f + "." + fmt).c_str());
    webServer.send(200, "text/plain", out);
}

void handleLogs()
{
    webServer.setContentLength(CONTENT_LENGTH_UNKNOWN);
    webServer.send(200, "text/html", "");
    pageHead("Session logs");
    String b;
    b += "<p class='warn'>Logs may contain VINs and vehicle data — local "
         "only, never uploaded.</p>";
    b += "<table><tr><th>File</th><th>Size</th><th colspan='4'>Download</th></tr>";
    for (uint8_t i = 0; i < p12::LOG_FILE_N; i++) {
        char path[32], idx[4];
        p12::logPath(i, path, sizeof(path));
        snprintf(idx, sizeof(idx), "%02u", i);
        b += "<tr><td>" + String(path) + "</td>";
        if (SPIFFS.exists(path)) {
            File fh = SPIFFS.open(path, "r");
            size_t sz = fh.size();
            fh.close();
            b += "<td>" + String(sz) + " B</td>";
            b += "<td><a href='/log_dl?f=" + String(idx) + "&fmt=native'>native</a></td>";
            b += "<td><a href='/log_dl?f=" + String(idx) + "&fmt=crtd'>CRTD</a></td>";
            b += "<td><a href='/log_dl?f=" + String(idx) + "&fmt=csv'>CSV</a></td>";
            b += "<td><a href='/log_dl?f=" + String(idx) + "&fmt=gvret'>GVRET*</a></td>";
        } else {
            b += "<td colspan='5'>(empty)</td>";
        }
        b += "</tr>";
    }
    b += "</table>";
    b += "<p>*GVRET download: kind-0 records as 0xF1 binary frames "
         "(CAN ID low 16 bits — the 23-byte record truncates full 29-bit "
         "IDs; see docs).</p>";
    b += "<p><a href='/phase12'>back</a></p>";
    webServer.sendContent(b);
    pageFoot();
    webServer.sendContent("");
}

