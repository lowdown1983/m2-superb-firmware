// Bee UART -> clients, with the control-channel diverter.
void pumpBeeRx()
{
    size_t n = 0;
    // S2: stop one byte short of PIPE_CHUNK. The RX diverter's GOT_F1
    // state needs TWO output slots to replay a held F1 plus the current
    // byte; with n == PIPE_CHUNK - 1 both would be silently discarded.
    // One byte of headroom guarantees every diverter output path fits.
    while (Serial.available() > 0 && n < PIPE_CHUNK - 1) {
        mmc::rxByte((uint8_t)Serial.read(), pipeBuf, n, PIPE_CHUNK);
    }
    if (n > 0) {
        // Phase 3: in OBD2 mode the Bee link carries poller CSV lines —
        // sniff them into the ring buffer for the web live view. (The mode
        // is cached from the last web status fetch; INFERRED timing.)
        if (m2status.ok && m2status.mode == 5) csvFeed(pipeBuf, n);
        // Phase 4: in MITM mode the Bee link carries MITMLOG lines from
        // LOG-action rules — sniff them for the /mitm live view.
        if (m2status.ok && m2status.mode == 4) mitmLogFeed(pipeBuf, n);
        if (SerialBT.hasClient()) SerialBT.write(pipeBuf, n);
        for (int i = 0; i < MAX_TCP_CLIENTS; i++)
            if (tcpClients[i] && tcpClients[i].connected())
                tcpClients[i].write(pipeBuf, n);
        // Phase 11: WebSocket binary clients join the broadcast (monitors
        // and owner alike — RX is never gated, only TX is).
        if (n > 0 && ws::nClients() > 0) webSocket.broadcastBIN(pipeBuf, n);
    }
}

// One client -> Bee UART, through the injection filter.
// Phase 11: single-owner policy — a non-owner's bytes never reach the M2.
bool pumpClientToUart(WiFiClient& client, uint8_t idx)
{
    if (!client.connected()) return false;
    size_t n = 0;
    while (client.available() > 0 && n < PIPE_CHUNK) {
        pipeBuf[n++] = (uint8_t)client.read();
    }
    if (n > 0) {
        if (own::txAllowed(own::T::TCP, idx)) {
            pwr::markActivity();
            mmc::uartWriteFiltered(pipeBuf, n);
        } else {
            own::dropped(n);
        }
    }
    return true;
}

void pumpBtToUart()
{
    if (!SerialBT.hasClient()) return;
    size_t n = 0;
    while (SerialBT.available() > 0 && n < PIPE_CHUNK) {
        pipeBuf[n++] = (uint8_t)SerialBT.read();
    }
    // Phase 11: single-owner policy — a non-owner's bytes never reach the M2.
    if (n > 0) {
        if (own::txAllowed(own::T::BT, 0)) {
            pwr::markActivity();
            mmc::uartWriteFiltered(pipeBuf, n);
        } else {
            own::dropped(n);
        }
    }
}

