void handleOtaUploadData()
{
    HTTPUpload& up = webServer.upload();
    if (up.status == UPLOAD_FILE_START) {
        if (!requireRole(auth::Role::ADMIN)) {
            ota::up.error = true;
            ota::up.msg = "login required (admin)";
            ota::up.active = false;
            return;
        }
        // Defensive: a previous upload abandoned mid-stream (client
        // disconnected before UPLOAD_FILE_END) leaves Update begun.
        if (ota::up.begun) Update.abort();
        ota::up.active = true;
        ota::up.error = false;
        ota::up.msg = "";
        ota::up.headN = 0;
        ota::up.begun = false;
        ota::up.version = 0;
        ota::up.imgLen = 0;
        ota::up.got = 0;
    } else if (up.status == UPLOAD_FILE_WRITE) {
        if (ota::up.error || !ota::up.active) return;
        pwr::markActivity();  // Phase 11: an in-progress upload is activity
        const uint8_t* d = up.buf;
        size_t n = up.currentSize;
        while (n > 0 && ota::up.headN < sizeof(ota::up.head)) {
            ota::up.head[ota::up.headN++] = *d++;
            n--;
        }
        if (ota::up.headN < sizeof(ota::up.head)) return;  // header incomplete
        if (!ota::up.begun) {
            if (memcmp(ota::up.head, "M2SBOTA1", 8) != 0) {
                ota::fail("bad magic (not a SuperB OTA package)");
                return;
            }
            uint32_t ver = (uint32_t)ota::up.head[8] |
                           ((uint32_t)ota::up.head[9] << 8) |
                           ((uint32_t)ota::up.head[10] << 16) |
                           ((uint32_t)ota::up.head[11] << 24);
            uint32_t len = (uint32_t)ota::up.head[12] |
                           ((uint32_t)ota::up.head[13] << 8) |
                           ((uint32_t)ota::up.head[14] << 16) |
                           ((uint32_t)ota::up.head[15] << 24);
            if (ver == 0 || ver <= ota::storedVer()) {
                ota::fail("anti-rollback: version not newer than installed");
                return;
            }
            if (len < ota::MIN_IMG || len > ota::MAX_IMG) {
                ota::fail("bad image length");
                return;
            }
            if (!Update.begin(len)) {
                ota::fail("Update.begin failed (OTA partitions present?)");
                return;
            }
            ota::up.version = ver;
            ota::up.imgLen = len;
            mbedtls_sha256_init(&ota::up.sha);
            mbedtls_sha256_starts_ret(&ota::up.sha, 0);
            // Signature covers header (16B) || image — not the sig itself.
            mbedtls_sha256_update_ret(&ota::up.sha, ota::up.head,
                                      ota::HDR_LEN);
            ota::up.begun = true;
        }
        if (n > 0) {
            mbedtls_sha256_update_ret(&ota::up.sha, d, n);
            if (Update.write((uint8_t*)d, n) != n) {
                ota::fail("Update.write failed");
                return;
            }
            ota::up.got += (uint32_t)n;
        }
    } else if (up.status == UPLOAD_FILE_ABORTED) {
        // Reviewer m3: client disconnected mid-upload. Fail explicitly so
        // a stale begun Update can't poison the next attempt (the START
        // handler also defensively aborts).
        ota::fail("upload aborted by client");
    } else if (up.status == UPLOAD_FILE_END) {
        if (ota::up.error || !ota::up.active) {
            ota::up.active = false;
            return;
        }
        if (!ota::up.begun || ota::up.got != ota::up.imgLen) {
            ota::fail("short image");
            return;
        }
        uint8_t hash[32];
        mbedtls_sha256_finish_ret(&ota::up.sha, hash);
        mbedtls_sha256_free(&ota::up.sha);
        if (!ota::verifySig(hash, ota::up.head + ota::HDR_LEN)) {
            ota::fail("signature invalid (wrong key?)");
            return;
        }
        // Reviewer m4: record the version BEFORE Update.end() commits the
        // image. A power loss in the reverse order would boot the new
        // image with a stale ota_ver, weakening the next anti-rollback
        // check. (If end() then fails, a same-version retry is rejected —
        // bump the version and retry; the old image still boots.)
        prefs.putUInt("ota_ver", ota::up.version);
        if (!Update.end() || Update.hasError()) {
            ota::fail("Update.end failed");
            return;
        }
        prefs.putUInt("ota_last", 1);
        ota::up.active = false;
        ota::up.msg = "verified + staged (version " +
                      String(ota::up.version) + "); reboot to run it";
    }
}

