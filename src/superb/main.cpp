//      GVRET/AT traffic never contains this pair (SavvyCAN commands are
//      0-14/0xE7; AT is text), so the filter is transparent to real apps.
//   2. RX DIVERTER (M2 -> apps): F1 7E frames from the M2 are extracted and
//      routed to the pending web-GUI request instead of being broadcast to
//      apps. Everything else broadcasts as before.
//   The web GUI sends commands with mmTransact() and matches replies by
//   command byte.
//
// Web GUI (Phase 2, NEW): HTTP on port 80. Hand-written HTML, no framework.
//   /            status (M2 mode, buses, features, network, clients)
//   /mode        mode-switch form (implemented modes only)
//   /mode_set    POST: executes the switch via the control channel (confirm)
//   /settings    bus settings + feature toggles form
//   /settings_set POST: applies via the control channel
//   /wifi        AP password + STA credentials form (NVS)
//   /wifi_set    POST: saves to NVS and restarts
//   /api/status  JSON status for polling
//
