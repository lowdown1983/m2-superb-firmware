// ---- PROG (programming) mode page ----
// READ docs/SAFETY_REVIEW.md. Web half of the interlocks: per-step confirm
// checkboxes (+ power attestation), arm-before-action via CMD_PROG_ARM,
// streaming chunked upload (CRC16 per chunk, CRC32 end-to-end).
// NOTE: the ESP32 WebServer handles one client at a time, so the upload
// uses XHR with client-side progress events — the server cannot serve
// /api/prog polls mid-upload (single-threaded by library design).

uint16_t progCrc16(const uint8_t* d, uint16_t n)
{
    uint16_t c = 0xFFFF;
    for (uint16_t i = 0; i < n; i++) {
        c ^= (uint16_t)d[i] << 8;
        for (uint8_t b = 0; b < 8; b++)
            c = (c & 0x8000) ? (uint16_t)((c << 1) ^ 0x1021) : (uint16_t)(c << 1);
    }
    return c;
}

uint32_t progCrcTab[256];
bool progCrcTabOk = false;
void progCrcInit()
{
    if (progCrcTabOk) return;
    for (uint32_t i = 0; i < 256; i++) {
        uint32_t c = i;
        for (uint8_t b = 0; b < 8; b++)
            c = (c & 1) ? (0xEDB88320UL ^ (c >> 1)) : (c >> 1);
        progCrcTab[i] = c;
    }
    progCrcTabOk = true;
}
uint32_t progCrc32feed(uint32_t crc, const uint8_t* d, size_t n)
{
    for (size_t i = 0; i < n; i++)
        crc = progCrcTab[(crc ^ d[i]) & 0xFF] ^ (crc >> 8);
    return crc;
}

struct ProgStatus {
    bool ok = false;
    uint8_t state = 0, session = 1, bus = 0;
    uint32_t baud = 500000, txId = 0x7E0, rxId = 0x7E8;
    uint8_t configured = 0, powerOk = 0, armed = 0;
    uint32_t bytesRx = 0;
    uint16_t chunksRx = 0;
    uint32_t txCrc = 0;
    uint8_t mitmSuspended = 0;
};
ProgStatus progSt;

const char* progStateName(uint8_t s)
{
    switch (s) {
        case 0: return "IDLE";
        case 1: return "SESSION";
        case 2: return "UNLOCKED";
        case 3: return "ERASED";
        case 4: return "DOWNLOADING";
        case 5: return "STREAM_DONE";
        case 6: return "DONE";
        case 7: return "ABORTED";
        case 8: return "ERROR";
        default: return "?";
    }
}

bool fetchProgStatus()
{
    uint8_t resp[64]; uint8_t rlen = 0;
    if (!mmcTransact(mmc::CMD_PROG_STATUS, nullptr, 0, resp, sizeof(resp), rlen) ||
        rlen < 31 || resp[0] != (mmc::CMD_PROG_STATUS | 0x80) ||
        resp[1] != mmc::ST_OK) {
        progSt.ok = false;
        return false;
    }
    progSt.ok = true;
    progSt.state = resp[2]; progSt.session = resp[3]; progSt.bus = resp[4];
    progSt.baud = (uint32_t)resp[5] | ((uint32_t)resp[6] << 8) |
                  ((uint32_t)resp[7] << 16) | ((uint32_t)resp[8] << 24);
    progSt.txId = (uint32_t)resp[9] | ((uint32_t)resp[10] << 8) |
                  ((uint32_t)resp[11] << 16) | ((uint32_t)resp[12] << 24);
    progSt.rxId = (uint32_t)resp[13] | ((uint32_t)resp[14] << 8) |
                  ((uint32_t)resp[15] << 16) | ((uint32_t)resp[16] << 24);
    progSt.configured = resp[17]; progSt.powerOk = resp[18]; progSt.armed = resp[19];
    progSt.bytesRx = (uint32_t)resp[20] | ((uint32_t)resp[21] << 8) |
                     ((uint32_t)resp[22] << 16) | ((uint32_t)resp[23] << 24);
    progSt.chunksRx = (uint16_t)resp[24] | ((uint16_t)resp[25] << 8);
    progSt.txCrc = (uint32_t)resp[26] | ((uint32_t)resp[27] << 8) |
                   ((uint32_t)resp[28] << 16) | ((uint32_t)resp[29] << 24);
    progSt.mitmSuspended = resp[30];
    return true;
}

// ---- upload streaming state ----
struct ProgUpload {
    bool active = false;
    bool error = false;
    bool done = false;
    String errorMsg;
    uint32_t bytes = 0;
    uint32_t total = 0;   // Content-Length when the client sent one
    uint16_t chunks = 0;
    uint16_t seq = 0;
    uint32_t crc32 = 0xFFFFFFFFUL;
    uint8_t acc[41];
    uint8_t accN = 0;
};
ProgUpload progUp;

bool progSendChunk(const uint8_t* data, uint8_t len, bool last)
{
    uint8_t req[6 + 41];
    req[0] = (uint8_t)(progUp.seq & 0xFF);
    req[1] = (uint8_t)((progUp.seq >> 8) & 0xFF);
    req[2] = last ? 1 : 0;
    req[3] = len;
    for (uint8_t i = 0; i < len; i++) req[4 + i] = data[i];
    uint16_t c = progCrc16(data, len);
    req[4 + len] = (uint8_t)(c & 0xFF);
    req[5 + len] = (uint8_t)((c >> 8) & 0xFF);
    uint8_t resp[64]; uint8_t rlen = 0;
    // The M2 turns each chunk into one 0x36 with a long ECU timeout.
    bool ok = mmcTransact(mmc::CMD_PROG_DATA, req, (uint8_t)(6 + len),
                          resp, sizeof(resp), rlen, 8000);
    if (!ok || rlen < 4 || resp[0] != (mmc::CMD_PROG_DATA | 0x80) ||
        resp[1] != mmc::ST_OK)
        return false;
    uint16_t ack = (uint16_t)resp[2] | ((uint16_t)resp[3] << 8);
    if (ack != progUp.seq) return false;
    progUp.seq++;
    progUp.chunks++;
    return true;
}

void handleProgUploadData()
{
    HTTPUpload& up = webServer.upload();
    if (up.status == UPLOAD_FILE_START) {
        // Phase 11: refuse the stream itself when not admin
        // (the M2's arm state is the backstop, not the gate).
        if (!requireRole(auth::Role::ADMIN)) {
            progUp.active = false; progUp.error = true; progUp.done = false;
            progUp.errorMsg = "login required (admin)";
            return;
        }
        progUp.active = true; progUp.error = false; progUp.done = false;
        progUp.errorMsg = "";
        progUp.bytes = 0; progUp.chunks = 0; progUp.seq = 0;
        progUp.crc32 = 0xFFFFFFFFUL; progUp.accN = 0;
        progUp.total = up.totalSize;
        progCrcInit();
    } else if (up.status == UPLOAD_FILE_WRITE) {
        if (progUp.error) return;
        pwr::markActivity();  // Phase 11: an in-progress upload is activity
        progUp.crc32 = progCrc32feed(progUp.crc32, up.buf, up.currentSize);
        for (size_t i = 0; i < up.currentSize; i++) {
            progUp.acc[progUp.accN++] = up.buf[i];
            progUp.bytes++;
            if (progUp.accN == 41) {
                if (!progSendChunk(progUp.acc, 41, false)) {
                    progUp.error = true;
                    progUp.errorMsg =
                        "chunk rejected by M2 (state/sequence/CRC) — transfer aborted";
                    return;
                }
                progUp.accN = 0;
            }
        }
    } else if (up.status == UPLOAD_FILE_END) {
        if (!progUp.error) {
            // Final partial chunk — or a zero-length LAST if the file
            // ended exactly on a chunk boundary (the M2 treats an empty
            // LAST chunk as end-of-stream with no 0x36).
            if (!progSendChunk(progUp.acc, progUp.accN, true)) {
                progUp.error = true;
                progUp.errorMsg = "final chunk rejected by M2";
            }
        }
        progUp.active = false;
        progUp.done = !progUp.error;
    }
}

