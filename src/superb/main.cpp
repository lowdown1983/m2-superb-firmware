struct Pending {
    bool active = false;
    uint8_t cmd = 0;
    uint8_t resp[64];
    uint8_t respLen = 0;
    bool got = false;
};
Pending pending;

// RX diverter state (M2 -> us).
enum class DState : uint8_t { IDLE, GOT_F1, LEN, PAYLOAD, XOR };
DState ds = DState::IDLE;
uint8_t dLen = 0, dPos = 0, dXor = 0;
uint8_t dBuf[64];

void handleReply()
{
    if (dLen < 2) return;
    // S3: require the exact reply opcode (request | 0x80). The old
    // (dBuf[0] & 0x7F) comparison also accepted a bare request opcode,
    // letting a checksum-valid false candidate complete a transaction.
    if (pending.active && dBuf[0] == (uint8_t)(pending.cmd | 0x80) && !pending.got) {
        pending.respLen = (dLen <= sizeof(pending.resp)) ? dLen : sizeof(pending.resp);
        for (uint8_t i = 0; i < pending.respLen; i++) pending.resp[i] = dBuf[i];
        pending.got = true;
    }
}

// Process one Bee-UART byte. Non-diverted bytes accumulate in outBuf for
// broadcast; returns via outN. Diverted control frames are consumed.
void rxByte(uint8_t c, uint8_t* outBuf, size_t& outN, size_t outCap)
{
    switch (ds) {
        case DState::IDLE:
            if (c == SYNC) ds = DState::GOT_F1;
            else if (outN < outCap) outBuf[outN++] = c;
            break;
        case DState::GOT_F1:
            if (c == CH) { ds = DState::LEN; }
            else if (c == SYNC) {
                // F1 F1 7E edge: emit the held F1, keep holding the new one.
                if (outN < outCap) outBuf[outN++] = SYNC;
            } else {
                // Not a control frame: emit the held F1 + this byte.
                if (outN + 2 <= outCap) { outBuf[outN++] = SYNC; outBuf[outN++] = c; }
                ds = DState::IDLE;
            }
            break;
        case DState::LEN:
            dLen = c; dPos = 0; dXor = 0;
            ds = (dLen == 0 || dLen > sizeof(dBuf)) ? DState::IDLE : DState::PAYLOAD;
            break;
        case DState::PAYLOAD:
            dBuf[dPos++] = c; dXor ^= c;
            if (dPos >= dLen) ds = DState::XOR;
            break;
        case DState::XOR:
            if (c == dXor) handleReply();  // bad XOR: drop silently
            ds = DState::IDLE;
            break;
    }
}

// TX filter state (apps -> M2): 1-byte hold-back so an F1 7E pair can be
// dropped before it hits the wire.
bool txHoldF1 = false;
uint32_t txHoldSince = 0;

void uartWriteFiltered(const uint8_t* data, size_t len)
{
    for (size_t i = 0; i < len; i++) {
        uint8_t c = data[i];
        if (txHoldF1) {
            txHoldF1 = false;
            if (c == CH) continue;  // drop the pair: injection attempt
            Serial.write(SYNC);     // lone F1: emit it now
        }
        if (c == SYNC) { txHoldF1 = true; txHoldSince = millis(); continue; }
        Serial.write(c);
    }
}

void txFilterIdle()
{
    // Flush a held F1 after 50 ms of client quiet (INFERRED; closes the
    // split-packet race without delaying normal traffic).
    if (txHoldF1 && (uint32_t)(millis() - txHoldSince) > 50) {
        txHoldF1 = false;
        Serial.write(SYNC);
    }
}

void txFilterReset()  // client disconnect: don't hold a byte forever
{
    if (txHoldF1) { txHoldF1 = false; Serial.write(SYNC); }
}
