// Shared: build the 21-byte map payload from form args. Returns false on
// bad args.
bool gwBuildPayload(uint8_t* req)
{
    long srcbus, dstbus, srcext, dstext, action, policy;
    long modoff = 0;
    uint32_t srcid, srcmask, dstid, modmask = 0, modval = 0;
    bool bad = !parseDecArg("srcbus", 0, 1, srcbus) ||
               !parseHexArg("srcid", 0x1FFFFFFFUL, srcid) ||
               !parseHexArg("srcmask", 0x1FFFFFFFUL, srcmask) ||
               !parseDecArg("srcext", 0, 1, srcext) ||
               !parseDecArg("dstbus", 0, 1, dstbus) ||
               !parseHexArg("dstid", 0x1FFFFFFFUL, dstid) ||
               !parseDecArg("dstext", 0, 1, dstext) ||
               !parseDecArg("action", 0, 1, action) ||
               !parseDecArg("policy", 0, 2, policy);
    if (!bad && action == 1) {
        long mo = 0;
        bad = !parseDecArg("modoff", 0, 7, mo);
        modoff = (uint32_t)mo;
        bad = bad || !parseHexArg("modmask", 0xFF, modmask) ||
              !parseHexArg("modval", 0xFF, modval);
    }
    if (bad || srcbus == dstbus) return false;
    req[0] = (uint8_t)srcbus;
    req[1] = (uint8_t)(srcid & 0xFF); req[2] = (uint8_t)((srcid >> 8) & 0xFF);
    req[3] = (uint8_t)((srcid >> 16) & 0xFF); req[4] = (uint8_t)((srcid >> 24) & 0xFF);
    req[5] = (uint8_t)(srcmask & 0xFF); req[6] = (uint8_t)((srcmask >> 8) & 0xFF);
    req[7] = (uint8_t)((srcmask >> 16) & 0xFF); req[8] = (uint8_t)((srcmask >> 24) & 0xFF);
    req[9] = (uint8_t)srcext;
    req[10] = (uint8_t)dstbus;
    req[11] = (uint8_t)(dstid & 0xFF); req[12] = (uint8_t)((dstid >> 8) & 0xFF);
    req[13] = (uint8_t)((dstid >> 16) & 0xFF); req[14] = (uint8_t)((dstid >> 24) & 0xFF);
    req[15] = (uint8_t)dstext;
    req[16] = (uint8_t)action;
    req[17] = (uint8_t)modoff; req[18] = (uint8_t)modmask; req[19] = (uint8_t)modval;
    req[20] = (uint8_t)policy;
    return true;
}

