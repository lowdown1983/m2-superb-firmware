struct GwMap {
    uint8_t idx = 0, srcBus = 0, srcExt = 0, dstBus = 1, dstExt = 0;
    uint8_t action = 0, modOff = 0, modMask = 0, modVal = 0, dropPolicy = 2;
    uint32_t srcId = 0, srcMask = 0, dstId = 0;
};
struct GwState {
    bool ok = false;
    uint32_t fwdCS = 0, fwdSC = 0, dropCS = 0, dropSC = 0, modCS = 0, modSC = 0;
    uint16_t version = 0;
    uint8_t nMaps = 0, suspended = 0, active = 0;
    uint32_t canBaud = 500000, swcanSpeed = 33333;
    uint8_t dropPolicy = 0, drainPerLoop = 4;
    GwMap maps[8];
    uint8_t nMapsGot = 0;
};
GwState gwSt;

bool fetchGwState()
{
    uint8_t resp[64]; uint8_t rlen = 0;
    if (!mmcTransact(mmc::CMD_GW_STATS, nullptr, 0, resp, sizeof(resp), rlen) ||
        rlen < 31 || resp[0] != (mmc::CMD_GW_STATS | 0x80) ||
        resp[1] != mmc::ST_OK) {
        gwSt.ok = false;
        return false;
    }
    gwSt.ok = true;
    gwSt.fwdCS = le32(resp + 2);  gwSt.fwdSC = le32(resp + 6);
    gwSt.dropCS = le32(resp + 10); gwSt.dropSC = le32(resp + 14);
    gwSt.modCS = le32(resp + 18); gwSt.modSC = le32(resp + 22);
    gwSt.version = (uint16_t)resp[26] | ((uint16_t)resp[27] << 8);
    gwSt.nMaps = resp[28]; gwSt.suspended = resp[29]; gwSt.active = resp[30];
    // Config readback (prefill the form honestly).
    if (mmcTransact(mmc::CMD_GW_CFG, nullptr, 0, resp, sizeof(resp), rlen) &&
        rlen >= 14 && resp[0] == (mmc::CMD_GW_CFG | 0x80) &&
        resp[1] == mmc::ST_OK) {
        gwSt.canBaud = le32(resp + 2); gwSt.swcanSpeed = le32(resp + 6);
        gwSt.dropPolicy = resp[10]; gwSt.drainPerLoop = resp[11];
        gwSt.active = resp[12]; gwSt.suspended = resp[13];
    }
    // Mapping list (1 per reply).
    gwSt.nMapsGot = 0;
    for (uint8_t start = 0; start < 8; start++) {
        uint8_t req[1] = { start };
        if (!mmcTransact(mmc::CMD_GW_MAP_LIST, req, 1, resp, sizeof(resp), rlen) ||
            rlen < 6 || resp[0] != (mmc::CMD_GW_MAP_LIST | 0x80) ||
            resp[1] != mmc::ST_OK)
            break;
        uint8_t nTotal = resp[2], nRet = resp[3];
        if (nRet > 1) nRet = 1;
        for (uint8_t i = 0; i < nRet && gwSt.nMapsGot < 8; i++) {
            const uint8_t* e = resp + 6 + i * 22;
            GwMap& m = gwSt.maps[gwSt.nMapsGot++];
            m.idx = e[0]; m.srcBus = e[1];
            m.srcId = le32(e + 2); m.srcMask = le32(e + 6);
            m.srcExt = e[10]; m.dstBus = e[11];
            m.dstId = le32(e + 12); m.dstExt = e[16];
            m.action = e[17]; m.modOff = e[18]; m.modMask = e[19];
            m.modVal = e[20]; m.dropPolicy = e[21];
        }
        if (start + nRet >= nTotal) break;
    }
    return true;
}

