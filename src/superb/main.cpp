void handleObd2Cfg()
{
    if (!requireRole(auth::Role::OPERATOR)) {
        denyPage(auth::Role::OPERATOR);
        return;
    }
    uint8_t pids[16]; uint8_t nPids = 0;
    bool bad = false;
    if (webServer.hasArg("pids")) {
        String s = webServer.arg("pids");
        int st = 0, L = s.length();
        while (st < L && nPids < 16) {
            int en = s.indexOf(',', st);
            if (en < 0) en = L;
            String tok = s.substring(st, en);
            tok.trim();
            // Take the last two hex digits ("010C" -> "0C").
            if (tok.length() > 2) tok = tok.substring(tok.length() - 2);
            char* e; long v = strtol(tok.c_str(), &e, 16);
            if (*e != '\0' || v < 0 || v > 0xFF) { bad = true; break; }
            pids[nPids++] = (uint8_t)v;
            st = en + 1;
        }
    }
    uint16_t interval = webServer.hasArg("interval")
        ? (uint16_t)webServer.arg("interval").toInt() : 1000;
    uint8_t bus = webServer.hasArg("bus") ? (uint8_t)webServer.arg("bus").toInt() : 0;
    uint32_t baud = webServer.hasArg("baud") ? (uint32_t)webServer.arg("baud").toInt() : 500000;
    webServer.setContentLength(CONTENT_LENGTH_UNKNOWN);
    webServer.send(200, "text/html", "");
    pageHead("OBD2 poller");
    String b;
    if (bad || nPids == 0) {
        b = "<p class='warn'>Bad PID list.</p>";
    } else {
        uint8_t req[8 + 16];
        req[0] = bus;
        req[1] = (uint8_t)(baud & 0xFF); req[2] = (uint8_t)((baud >> 8) & 0xFF);
        req[3] = (uint8_t)((baud >> 16) & 0xFF); req[4] = (uint8_t)((baud >> 24) & 0xFF);
        req[5] = (uint8_t)(interval & 0xFF); req[6] = (uint8_t)((interval >> 8) & 0xFF);
        req[7] = nPids;
        for (uint8_t i = 0; i < nPids; i++) req[8 + i] = pids[i];
        uint8_t resp[64]; uint8_t rlen = 0;
        bool ok = mmcTransact(mmc::CMD_OBD2_CFG, req, (uint8_t)(8 + nPids), resp, sizeof(resp), rlen);
        b = (ok && rlen >= 2 && resp[1] == mmc::ST_OK)
            ? "<p>Config applied (" + String(nPids) + " PIDs). Poller stopped — press Start.</p>"
            : "<p class='warn'>Failed (bad args?).</p>";
    }
    b += "<p><a href='/obd2'>Back</a></p>";
    webServer.sendContent(b);
    pageFoot();
    webServer.sendContent("");
}

