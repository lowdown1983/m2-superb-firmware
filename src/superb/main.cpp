const char* nrcText(uint8_t nrc)  // ISO 14229-1 (mirrors src/m2/mode_uds.h)
{
    switch (nrc) {
        case 0x10: return "generalReject";
        case 0x11: return "serviceNotSupported";
        case 0x12: return "subFunctionNotSupported";
        case 0x13: return "incorrectMessageLengthOrInvalidFormat";
        case 0x21: return "busyRepeatRequest";
        case 0x22: return "conditionsNotCorrect";
        case 0x24: return "requestSequenceError";
        case 0x25: return "noResponseFromSubnetComponent";
        case 0x26: return "failurePreventsExecutionOfRequestedAction";
        case 0x31: return "requestOutOfRange";
        case 0x33: return "securityAccessDenied";
        case 0x35: return "invalidKey";
        case 0x36: return "exceedNumberOfAttempts";
        case 0x37: return "requiredTimeDelayNotExpired";
        case 0x70: return "uploadDownloadNotAccepted";
        case 0x71: return "transferDataSuspended";
        case 0x72: return "generalProgrammingFailure";
        case 0x73: return "wrongBlockSequenceCounter";
        case 0x78: return "requestCorrectlyReceived_ResponsePending";
        case 0x7E: return "subFunctionNotSupportedInActiveSession";
        case 0x7F: return "serviceNotSupportedInActiveSession";
        default:   return "unknown NRC";
    }
}

// Parse "22 F190" / "22F190" / "22 f1 90" into bytes. Returns count or -1.
int hexToBytes(const String& s, uint8_t* out, uint8_t cap)
{
    uint8_t n = 0;
    int i = 0, L = s.length();
    while (i < L) {
        while (i < L && (s[i] == ' ' || s[i] == '\t' || s[i] == ',')) i++;
        if (i >= L) break;
        if (i + 1 >= L || n >= cap) return -1;
        char tmp[3] = { s[i], s[i + 1], '\0' };
        char* e; long v = strtol(tmp, &e, 16);
        if (*e != '\0' || v < 0 || v > 0xFF) return -1;
        out[n++] = (uint8_t)v;
        i += 2;
    }
    return n;
}

String hexStr(const uint8_t* d, uint8_t n)
{
    static const char* H = "0123456789ABCDEF";
    String s;
    for (uint8_t i = 0; i < n; i++) {
        if (i) s += ' ';
        s += H[(d[i] >> 4) & 0xF];
        s += H[d[i] & 0xF];
    }
    return s;
}

struct UdsStatus {
    bool ok = false;
    uint8_t session = 1, bus = 0, func = 0, tpOn = 0;
    uint32_t baud = 500000, txId = 0x7E0, rxId = 0x7E8;
};
UdsStatus udsSt;

bool fetchUdsStatus()
{
    uint8_t resp[64]; uint8_t rlen = 0;
    if (!mmcTransact(mmc::CMD_UDS_STATUS, nullptr, 0, resp, sizeof(resp), rlen) ||
        rlen < 18 || resp[0] != (mmc::CMD_UDS_STATUS | 0x80) || resp[1] != mmc::ST_OK) {
        udsSt.ok = false;
        return false;
    }
    udsSt.ok = true;
    udsSt.session = resp[2]; udsSt.bus = resp[3];
    udsSt.baud = (uint32_t)resp[4] | ((uint32_t)resp[5] << 8) |
                 ((uint32_t)resp[6] << 16) | ((uint32_t)resp[7] << 24);
    udsSt.txId = (uint32_t)resp[8] | ((uint32_t)resp[9] << 8) |
                 ((uint32_t)resp[10] << 16) | ((uint32_t)resp[11] << 24);
    udsSt.rxId = (uint32_t)resp[12] | ((uint32_t)resp[13] << 8) |
                 ((uint32_t)resp[14] << 16) | ((uint32_t)resp[15] << 24);
    udsSt.func = resp[16]; udsSt.tpOn = resp[17];
    return true;
}

struct Obd2Status {
    bool ok = false;
    uint8_t running = 0, bus = 0, nPids = 0;
    uint16_t interval = 1000;
};
Obd2Status obd2St;

bool fetchObd2Status()
{
    uint8_t resp[64]; uint8_t rlen = 0;
    if (!mmcTransact(mmc::CMD_OBD2_STATUS, nullptr, 0, resp, sizeof(resp), rlen) ||
        rlen < 7 || resp[0] != (mmc::CMD_OBD2_STATUS | 0x80) || resp[1] != mmc::ST_OK) {
        obd2St.ok = false;
        return false;
    }
    obd2St.ok = true;
    obd2St.running = resp[2]; obd2St.bus = resp[3];
    obd2St.interval = (uint16_t)resp[4] | ((uint16_t)resp[5] << 8);
    obd2St.nPids = resp[6];
    return true;
}

// Send one raw UDS service; returns true and fills out with a human-
// readable result. needsConfirm: caller already checked the web checkbox.
bool udsSendRaw(uint8_t svc, const uint8_t* params, uint8_t nParams, String& out)
{
    uint8_t req[1 + 1 + 32];
    req[0] = (uint8_t)(1 + nParams);
    req[1] = svc;
    for (uint8_t i = 0; i < nParams; i++) req[2 + i] = params[i];
    uint8_t resp[64]; uint8_t rlen = 0;
    // F-03-02: the frame is [svcLen][svc][params...] = 2 + nParams bytes.
    // The old (1 + nParams) omitted the svcLen byte itself, so the M2
    // rejected every request (rxLen < 3, or svcLen > rxLen - 2).
    bool ok = mmcTransact(mmc::CMD_UDS_TX, req, (uint8_t)(2 + nParams), resp, sizeof(resp), rlen);
    if (!ok) { out = "<span class='warn'>M2 did not answer.</span>"; return false; }
    if (rlen < 2 || resp[1] != mmc::ST_OK) {
        out = "<span class='warn'>Rejected: switch the M2 to UDS mode first.</span>";
        return false;
    }
    uint8_t nResp = (rlen > 2) ? resp[2] : 0;
    uint8_t dlen = (rlen > 3) ? resp[3] : 0;
    out = "TX: " + hexStr(&svc, 1);
    if (nParams) out += " " + hexStr(params, nParams);
    out += "<br>";
    if (nResp == 0) {
        out += "NO DATA (no ECU answered)";
        return true;
    }
    out += "RX (" + String(nResp) + " ECU(s), first shown): " + hexStr(resp + 4, dlen);
    if (dlen >= 3 && resp[4] == 0x7F && resp[5] == svc) {
        uint8_t nrc = resp[6];
        out += "<br><span class='warn'>Negative response: " + String(nrcText(nrc)) +
               " (NRC 0x" + String(nrc, HEX) + ")</span>";
    } else if (dlen >= 1 && resp[4] == (uint8_t)(svc + 0x40)) {
        out += "<br>Positive response.";
    }
    return true;
}

