static bool parseHexArg(const char* name, uint32_t max, uint32_t& out)
{
    if (!webServer.hasArg(name)) return false;
    String s = webServer.arg(name);
    s.trim();
    char* e; unsigned long v = strtoul(s.c_str(), &e, 16);
    if (*e != '\0' || v > max) return false;
    out = (uint32_t)v;
    return true;
}

static bool parseDecArg(const char* name, long lo, long hi, long& out)
{
    if (!webServer.hasArg(name)) return false;
    String s = webServer.arg(name);
    s.trim();
    char* e; long v = strtol(s.c_str(), &e, 10);
    if (*e != '\0' || v < lo || v > hi) return false;
    out = v;
    return true;
}

