// Arm destructive PROG steps from a web checkbox. power=true also records
// the stable-12V+ attestation (a human promise, NOT a measurement).
bool progArmWeb(bool power, String& why)
{
    uint8_t req[1] = { (uint8_t)(power ? 1 : 0) };
    uint8_t resp[64]; uint8_t rlen = 0;
    bool ok = mmcTransact(mmc::CMD_PROG_ARM, req, 1, resp, sizeof(resp), rlen);
    if (!ok || rlen < 3 || resp[1] != mmc::ST_OK || resp[2] == 0) {
        why = "M2 refused to arm (is PROG mode active?)";
        return false;
    }
    return true;
}

// Send one raw PROG service; human-readable result in out. The caller must
// have armed first for destructive services (web checkbox -> progArmWeb).
bool progSendRaw(uint8_t svc, const uint8_t* params, uint8_t nParams,
                 String& out, uint16_t timeoutMs = 2000)
{
    // F2 (2026-10-08): req is 34B; reject oversized params instead of
    // overflowing the stack (handleProgKey could pass up to 65B).
    if (nParams > 32) {
        out = "<span class='warn'>Params too long (max 32).</span>";
        return false;
    }
    uint8_t req[1 + 1 + 32];
    req[0] = (uint8_t)(1 + nParams);
    req[1] = svc;
    for (uint8_t i = 0; i < nParams; i++) req[2 + i] = params[i];
    uint8_t resp[64]; uint8_t rlen = 0;
    bool ok = mmcTransact(mmc::CMD_PROG_TX, req, (uint8_t)(1 + nParams),
                          resp, sizeof(resp), rlen, timeoutMs);
    if (!ok) { out = "<span class='warn'>M2 did not answer.</span>"; return false; }
    if (rlen < 2 || resp[1] != mmc::ST_OK) {
        out = "<span class='warn'>Rejected: switch the M2 to PROG mode first.</span>";
        return false;
    }
    uint8_t nResp = (rlen > 2) ? resp[2] : 0;
    uint8_t dlen = (rlen > 3) ? resp[3] : 0;
    out = "TX: " + hexStr(&svc, 1);
    if (nParams) out += " " + hexStr(params, nParams);
    out += "<br>";
    if (nResp == 0) {
        out += "NO DATA (no ECU answered)";
        return true;
    }
    out += "RX: " + hexStr(resp + 4, dlen);
    if (dlen >= 3 && resp[4] == 0x7F && resp[5] == svc) {
        uint8_t nrc = resp[6];
        out += "<br><span class='warn'>Negative response: " + String(nrcText(nrc)) +
               " (NRC 0x" + String(nrc, HEX) + ")</span>";
    } else if (dlen >= 1 && resp[4] == (uint8_t)(svc + 0x40)) {
        out += "<br>Positive response.";
    }
    return true;
}

