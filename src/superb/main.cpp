bool configured() { return prefs.getBool("adm_set", false); }

void shaSalted(const uint8_t* salt, const String& pw, uint8_t* out32)
{
    mbedtls_sha256_context c;
    mbedtls_sha256_init(&c);
    mbedtls_sha256_starts_ret(&c, 0);
    mbedtls_sha256_update_ret(&c, salt, 16);
    mbedtls_sha256_update_ret(&c, (const uint8_t*)pw.c_str(), pw.length());
    mbedtls_sha256_finish_ret(&c, out32);
    mbedtls_sha256_free(&c);
}

bool eq32(const uint8_t* a, const uint8_t* b)
{
    uint8_t d = 0;
    for (int i = 0; i < 32; i++) d |= (uint8_t)(a[i] ^ b[i]);
    return d == 0;
}

// Check a password against the stored salted hash ("adm" or "opr").
bool checkPw(const char* which, const String& pw)
{
    char skey[16], hkey[16], fkey[16];
    snprintf(skey, sizeof(skey), "%s_salt", which);
    snprintf(hkey, sizeof(hkey), "%s_hash", which);
    snprintf(fkey, sizeof(fkey), "%s_set", which);
    if (!prefs.getBool(fkey, false)) return false;
    if (pw.length() < 1 || pw.length() > 64) return false;
    uint8_t salt[16], want[32], got[32];
    if (prefs.getBytes(skey, salt, sizeof(salt)) != sizeof(salt)) return false;
    if (prefs.getBytes(hkey, want, sizeof(want)) != sizeof(want)) return false;
    shaSalted(salt, pw, got);
    bool ok = eq32(want, got);
    memset(salt, 0, sizeof(salt));
    memset(got, 0, sizeof(got));
    return ok;
}

// Store a salted hash for "adm"/"opr". Empty password clears the account.
void setPw(const char* which, const String& pw)
{
    char skey[16], hkey[16], fkey[16];
    snprintf(skey, sizeof(skey), "%s_salt", which);
    snprintf(hkey, sizeof(hkey), "%s_hash", which);
    snprintf(fkey, sizeof(fkey), "%s_set", which);
    if (pw.length() == 0) {
        prefs.putBool(fkey, false);
        return;
    }
    uint8_t salt[16], h[32];
    for (int i = 0; i < 16; i += 4) {
        uint32_t r = esp_random();
        salt[i] = (uint8_t)(r & 0xFF);
        salt[i + 1] = (uint8_t)((r >> 8) & 0xFF);
        salt[i + 2] = (uint8_t)((r >> 16) & 0xFF);
        salt[i + 3] = (uint8_t)((r >> 24) & 0xFF);
    }
    shaSalted(salt, pw, h);
    prefs.putBytes(skey, salt, sizeof(salt));
    prefs.putBytes(hkey, h, sizeof(h));
    prefs.putBool(fkey, true);
    memset(salt, 0, sizeof(salt));
    memset(h, 0, sizeof(h));
}

String newSession(Role r)
{
    uint32_t now = millis();
    uint32_t tmo = prefs.getUInt("sess_tmo", 1800);
    int slot = -1;
    for (int i = 0; i < 4; i++) {
        if (!sess_[i].used ||
            (int32_t)(now - sess_[i].exp) >= 0) {
            slot = i;
            break;
        }
    }
    if (slot < 0) slot = 0;  // evict oldest slot
    static const char* H = "0123456789abcdef";
    for (int i = 0; i < 8; i++) {
        uint32_t rr = esp_random();
        sess_[slot].tok[2 * i] = H[(rr >> 4) & 0xF];
        sess_[slot].tok[2 * i + 1] = H[rr & 0xF];
    }
    sess_[slot].tok[16] = '\0';
    sess_[slot].used = true;
    sess_[slot].role = r;
    sess_[slot].exp = now + tmo * 1000UL;
    return String(sess_[slot].tok);
}

// Role of the current web request from the M2SB_SESS cookie.
// Unauthenticated (or expired) -> VIEWER.
Role webRole()
{
    String c = webServer.header("Cookie");
    int at = c.indexOf("M2SB_SESS=");
    if (at < 0) return Role::VIEWER;
    String tok = c.substring(at + 10, at + 26);
    uint32_t now = millis();
    for (int i = 0; i < 4; i++) {
        if (sess_[i].used && tok == sess_[i].tok) {
            if ((int32_t)(now - sess_[i].exp) >= 0) {
                sess_[i].used = false;
                return Role::VIEWER;
            }
            sess_[i].exp = now + prefs.getUInt("sess_tmo", 1800) * 1000UL;
            return sess_[i].role;
        }
    }
    return Role::VIEWER;
}

void logoutWeb()
{
    String c = webServer.header("Cookie");
    int at = c.indexOf("M2SB_SESS=");
    if (at < 0) return;
    String tok = c.substring(at + 10, at + 26);
    for (int i = 0; i < 4; i++)
        if (sess_[i].used && tok == sess_[i].tok) sess_[i].used = false;
}

