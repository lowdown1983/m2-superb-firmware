//
// Bridge (Phase 1, kept):
//   - Bluetooth Classic SPP ("M2-SuperB"): raw byte pipe to the Bee UART.
//   - WiFi AP+STA. Phase 2: AP is WPA2 (password in NVS, changeable via the
//     web GUI); STA credentials come from NVS (web GUI), no placeholders.
//   - TCP server on port 23: raw byte pipe to the Bee UART (SavvyCAN
//     GVRET-TCP target).
//
// Control channel (Phase 2, NEW):
//   The M2's multimode channel is framed as F1 7E LEN PAYLOAD XOR on the Bee
//   UART (see src/m2/mm_channel.h). Two proxy duties here:
//   1. TX FILTER (app -> M2): a connected app must never inject a control
