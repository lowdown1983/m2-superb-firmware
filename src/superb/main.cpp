void loop()
{
    pumpBeeRx();       // M2 -> clients (diverts control frames)
    pumpBtToUart();    // BT -> M2 (filtered, owner-gated)

    // Phase 11: BT disconnect releases ownership.
    static bool btWas = false;
    bool btNow = SerialBT.hasClient();
    if (btWas && !btNow) own::onDisconnect(own::T::BT, 0);
    btWas = btNow;

    for (int i = 0; i < MAX_TCP_CLIENTS; i++) {
        if (tcpClients[i]) {
            if (!pumpClientToUart(tcpClients[i], (uint8_t)i)) {
                tcpClients[i].stop();
                own::onDisconnect(own::T::TCP, (uint8_t)i);
                mmc::txFilterReset();
            }
        }
    }
    mmc::txFilterIdle();

    WiFiClient newcomer = tcpServer.available();
    if (newcomer) {
        int slot = -1;
        for (int i = 0; i < MAX_TCP_CLIENTS; i++) {
            if (!tcpClients[i] || !tcpClients[i].connected()) { slot = i; break; }
        }
        if (slot < 0) {
            own::onDisconnect(own::T::TCP, 0);
            tcpClients[0].stop(); slot = 0;
        }  // evict oldest
        tcpClients[slot] = newcomer;
    }

    webServer.handleClient();
    webSocket.loop();  // Phase 11: WebSocket transport

    // Phase 11: appliance supervision.
    own::poll();    // ownership idle timeout
    pair_::poll();   // pairing window (Button2)
    pwr::poll();     // voltage / modem doze / light sleep

    p12::sinkTick();  // Phase 12: log sink poll + SPIFFS rotation

    static uint32_t lastBlink = 0;
    static bool ledOn = false;
    uint32_t now = millis();
    // Phase 11: fast blink while the pairing window is open.
    uint32_t blinkMs = pair_::open() ? 150 : 1000;
    if (now - lastBlink >= blinkMs) {
        lastBlink = now;
        ledOn = !ledOn;
        digitalWrite(SUPERB_LED, ledOn ? HIGH : LOW);
    }
}
