// Forward: pumpBeeRx is defined below; mmcTransact needs it.
void pumpBeeRx();

// ---- mmcTransact: sends a control frame DIRECTLY (bypasses the TX filter
// ---- the SuperB is the legitimate sender) and waits for the reply.
bool mmcTransact(uint8_t cmd, const uint8_t* payload, uint8_t plen,
                 uint8_t* resp, uint8_t outCap, uint8_t& rlen,
                 uint16_t timeoutMs)
{
    using namespace mmc;
    if (plen > MAXP - 1) return false;
    uint8_t f[4 + MAXP];
    f[0] = SYNC; f[1] = CH; f[2] = (uint8_t)(1 + plen); f[3] = cmd;
    uint8_t x = cmd;
    for (uint8_t i = 0; i < plen; i++) { f[4 + i] = payload[i]; x ^= payload[i]; }
    f[4 + plen] = x;
    pending.active = true; pending.cmd = cmd; pending.got = false;
    pending.respLen = 0;
    Serial.write(f, (size_t)(5 + plen));  // direct: bypasses TX filter
    uint32_t deadline = millis() + timeoutMs;
    while (!pending.got && (int32_t)(millis() - deadline) < 0) {
        pumpBeeRx();
        delay(1);
    }
    pending.active = false;
    if (!pending.got) return false;
    // Audit fix C1 (2026-10-08): never copy more than the caller can hold.
    // respLen is clamped to sizeof(pending.resp)=64 by handleReply(); outCap
    // is the caller's buffer size (pass sizeof(resp) at every call site).
    rlen = (pending.respLen <= outCap) ? pending.respLen : outCap;
    for (uint8_t i = 0; i < rlen; i++) resp[i] = pending.resp[i];
    return true;
}

// M2 status snapshot for the web GUI.
struct M2Status {
    bool ok = false;
    uint8_t mode = 0;
    uint32_t can0 = 0, can1 = 0, swcan = 0;
    uint8_t features = 0;
};
M2Status m2status;

bool fetchM2Status()
{
    uint8_t resp[64]; uint8_t rlen = 0;
    if (!mmcTransact(mmc::CMD_GET_STATUS, nullptr, 0, resp, sizeof(resp), rlen)) {
        m2status.ok = false;
        return false;
    }
    if (rlen < 16 || resp[0] != (mmc::CMD_GET_STATUS | 0x80) || resp[1] != mmc::ST_OK) {
        m2status.ok = false;
        return false;
    }
    m2status.ok = true;
    m2status.mode = resp[2];
    m2status.can0 = (uint32_t)resp[3] | ((uint32_t)resp[4] << 8) |
                    ((uint32_t)resp[5] << 16) | ((uint32_t)resp[6] << 24);
    m2status.can1 = (uint32_t)resp[7] | ((uint32_t)resp[8] << 8) |
                    ((uint32_t)resp[9] << 16) | ((uint32_t)resp[10] << 24);
    m2status.swcan = (uint32_t)resp[11] | ((uint32_t)resp[12] << 8) |
                     ((uint32_t)resp[13] << 16) | ((uint32_t)resp[14] << 24);
    m2status.features = resp[15];
    return true;
}

